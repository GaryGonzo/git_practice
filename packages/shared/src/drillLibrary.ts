const body = (pose: Scene["pose"]): Scene => ({ set: "body", pose });
const swingScene = (pose: Scene["pose"], items: SceneItem[] = []): Scene => ({ set: "garage", pose, items });

function putts(set: Scene["set"], items: SceneItem[], targets: [number, number][], from: [number, number] = [50, 52]): Scene {
  return { set, pose: "putt", items, shots: targets.map((to) => ({ from, to })) };
}

function shots(set: Scene["set"], pose: Scene["pose"], items: SceneItem[], targets: [number, number][], from: [number, number] = [50, 55]): Scene {
  const s: SceneShot[] = targets.map((to) => ({ from, to, air: true }));
  return { set, pose, items, shots: s };
}

