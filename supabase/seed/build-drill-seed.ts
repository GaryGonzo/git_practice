// Builds the SQL that loads the Golfable v2 drill library into the drills
// table: upserts every drill in DRILL_LIBRARY and archives every drill that
// isn't in it (archived, never deleted -- past scores keep counting).
//
//   npx tsx supabase/seed/build-drill-seed.ts > supabase/migrations/0072_golfable_v2_drill_library.sql
//
// v1 columns are filled too (setup/rules/targets/max_score) so anything
// still reading them sees sensible values.

import { DRILL_LIBRARY, type LibraryDrill } from "../../packages/shared/src/index.ts";

function q(s: string | null | undefined): string {
  if (s === null || s === undefined) return "null";
  return `'${s.replace(/'/g, "''")}'`;
}

function arr(items: string[]): string {
  return `array[${items.map(q).join(", ")}]::text[]`;
}

function json(v: unknown): string {
  return v === undefined || v === null ? "null" : `${q(JSON.stringify(v))}::jsonb`;
}

function row(d: LibraryDrill, i: number): string {
  const s = d.score;
  const target = (band: "0-5" | "6-10" | "11-15" | "21+") => (s ? String(s.targets[band]) : "Done");
  const values = [
    q(d.id),
    q(d.name),
    `${q(d.category)}::skill_category`,
    q(d.steps[0]),
    arr(d.equipment),
    q(d.steps.slice(1).join(" ")),
    arr(s ? [s.label] : [d.reps ?? "Check it off when done"]),
    q(target("0-5")),
    q(target("6-10")),
    q(target("11-15")),
    q(target("21+")),
    String(s ? s.max : 1),
    q(s?.lower ? "lower" : "higher"),
    q("active"),
    arr(d.areas),
    arr(d.spots),
    q(d.needs),
    arr(d.aids ?? []),
    String(d.minutes),
    s ? "true" : "false",
    q(d.reps ?? null),
    arr(d.steps),
    q(s?.label ?? null),
    json(s?.targets ?? null),
    json(d.scene),
    q(d.kind),
    q(d.level ?? "all"),
    String(i),
  ];
  return `(${values.join(", ")})`;
}

const ids = DRILL_LIBRARY.map((d) => d.id);
if (new Set(ids).size !== ids.length) throw new Error("Duplicate drill id in DRILL_LIBRARY");

const columns = [
  "id",
  "name",
  "category",
  "setup_description",
  "setup_equipment",
  "rules_description",
  "rules_scoring",
  "target_scratch",
  "target_low",
  "target_mid",
  "target_high",
  "max_score",
  "score_direction",
  "status",
  "areas",
  "spots",
  "needs",
  "aids",
  "minutes",
  "scored",
  "reps_label",
  "steps",
  "score_label",
  "band_targets",
  "scene",
  "kind",
  "level",
  "sort_order",
];
const updates = columns.filter((c) => c !== "id").map((c) => `  ${c} = excluded.${c}`);

console.log(`-- Golfable v2 drill library (${DRILL_LIBRARY.length} drills). Generated by supabase/seed/build-drill-seed.ts -- edit packages/shared/src/drillLibrary.ts, not this file.

insert into drills (${columns.join(", ")}) values
${DRILL_LIBRARY.map(row).join(",\n")}
on conflict (id) do update set
${updates.join(",\n")};

-- Everything else is archived: out of sessions, but past scores still count.
update drills set status = 'archived' where id not in (${ids.map(q).join(", ")});
`);
